//! Генерация autoexec.cfg и строки параметров запуска из настроек ShaurMeaw.
//!
//! ВНИМАНИЕ: Deadlock в активной разработке, Valve может переименовывать консольные
//! переменные. Неизвестные команды игра просто игнорирует (пишет "Unknown command" в консоль).

use std::fmt::Write;

use crate::settings::{RenderApi, Settings, WindowMode};

/// Метка, по которой лаунчер узнаёт «свой» autoexec (чтобы не делать бэкап поверх бэкапа).
pub const MARKER: &str = "// Generated by ShaurMeaw";
/// Предыдущая метка (для совместимости при обновлении с версии 0.1).
pub const OLD_MARKER: &str = "// Generated by Deadlock Launcher";

fn b(v: bool) -> &'static str {
    if v {
        "1"
    } else {
        "0"
    }
}

/// Собирает содержимое autoexec.cfg.
pub fn build_autoexec(s: &Settings) -> String {
    let mut out = String::new();

    let _ = writeln!(out, "{MARKER}");
    let _ = writeln!(
        out,
        "// Файл перезаписывается лаунчером ShaurMeaw. Свои команды добавляйте во вкладке «Бинды и команды»."
    );
    let _ = writeln!(out);

    // --- Производительность
    let _ = writeln!(out, "// --- Производительность ---");
    let _ = writeln!(out, "fps_max {}", s.fps_max);
    let _ = writeln!(out, "cl_showfps {}", b(s.show_fps));
    if s.no_focus_sleep {
        // не снижать FPS, когда игра свёрнута / не в фокусе
        let _ = writeln!(out, "engine_no_focus_sleep 0");
    }
    let _ = writeln!(out, "snd_mute_losefocus {}", b(!s.sound_on_lost_focus));
    let _ = writeln!(out);

    // --- Оптимизация Source 2
    if s.low_latency_mode > 0
        || s.low_latency_sleep_after_tick
        || s.optimize_network
        || s.optimize_audio_latency
        || s.disable_ragdolls_decals
        || s.disable_shadows_autoexec
    {
        let _ = writeln!(out, "// --- Оптимизация Source 2 (FPS, Input Lag, Сеть, Звук) ---");
        if s.low_latency_mode > 0 {
            let _ = writeln!(out, "r_low_latency {}", s.low_latency_mode.min(2));
        }
        if s.low_latency_sleep_after_tick {
            let _ = writeln!(out, "engine_low_latency_sleep_after_client_tick 1");
        }
        if s.optimize_network {
            let _ = writeln!(out, "rate 786432");
            let _ = writeln!(out, "cl_interp_ratio 1");
            let _ = writeln!(out, "cl_interp 0");
            let _ = writeln!(out, "net_maxroutable 1200");
        }
        if s.optimize_audio_latency {
            let _ = writeln!(out, "snd_mixahead 0.025");
            let _ = writeln!(out, "dsp_enhance_stereo 0");
            let _ = writeln!(out, "snd_spatialize_roundrobin 1");
        }
        if s.disable_ragdolls_decals {
            let _ = writeln!(out, "cl_ragdoll_limit 0");
            let _ = writeln!(out, "r_drawdecals 0");
            let _ = writeln!(out, "r_decals 0");
        }
        if s.disable_shadows_autoexec {
            let _ = writeln!(out, "lb_enable_shadow_casting 0");
            let _ = writeln!(out, "r_shadows 0");
        }
        let _ = writeln!(out);
    }

    // --- Геймплей и телеметрия HUD
    let gp = &s.gameplay;
    if gp.manage_volume
        || gp.manage_sensitivity
        || gp.telemetry_fps
        || gp.telemetry_ping
        || gp.telemetry_loss
    {
        let _ = writeln!(out, "// --- Геймплей и телеметрия HUD ---");
        if gp.manage_volume {
            let _ = writeln!(out, "volume {:.2}", gp.volume.clamp(0.0, 1.0));
        }
        if gp.manage_sensitivity {
            let _ = writeln!(out, "sensitivity {:.3}", gp.sensitivity.max(0.05));
        }
        if gp.telemetry_fps {
            let _ = writeln!(out, "cl_hud_telemetry_frametime_show 2");
        }
        if gp.telemetry_ping {
            let _ = writeln!(out, "cl_hud_telemetry_ping_show 2");
        }
        if gp.telemetry_loss {
            let _ = writeln!(out, "cl_hud_telemetry_net_misdelivery_show 2");
        }
        let _ = writeln!(out);
    }

    // --- Графика
    let g = &s.graphics;
    if g.enabled {
        let _ = writeln!(out, "// --- Графика ---");
        let _ = writeln!(out, "r_ssao {}", b(g.ssao));
        let _ = writeln!(out, "r_citadel_fog_quality {}", b(g.fog));
        let _ = writeln!(out, "r_citadel_outlines {}", b(g.outlines));
        let _ = writeln!(out, "r_depth_of_field {}", b(g.depth_of_field));
        let _ = writeln!(
            out,
            "r_citadel_distancefield_farfield_enable {}",
            b(g.farfield)
        );
        let _ = writeln!(out, "r_dashboard_render_quality {}", b(g.dashboard_hq));
        let _ = writeln!(out, "r_particle_max_detail_level {}", g.particle_detail);
        let _ = writeln!(out);
    }

    // --- Прицел
    let c = &s.crosshair;
    if c.enabled {
        let _ = writeln!(out, "// --- Прицел ---");
        let _ = writeln!(out, "citadel_crosshair_color_r {}", c.color[0]);
        let _ = writeln!(out, "citadel_crosshair_color_g {}", c.color[1]);
        let _ = writeln!(out, "citadel_crosshair_color_b {}", c.color[2]);
        let _ = writeln!(out, "citadel_crosshair_pip_gap {}", c.gap.round() as i32);
        let _ = writeln!(
            out,
            "citadel_crosshair_pip_width {}",
            c.width.round() as i32
        );
        let _ = writeln!(
            out,
            "citadel_crosshair_pip_height {}",
            c.height.round() as i32
        );
        let _ = writeln!(out, "citadel_crosshair_pip_opacity {:.2}", c.opacity);
        let _ = writeln!(out, "citadel_crosshair_pip_border {}", c.border);
        let _ = writeln!(out, "citadel_crosshair_dot_opacity {:.2}", c.dot_opacity);
        let _ = writeln!(
            out,
            "citadel_crosshair_dot_outline_opacity {:.2}",
            c.dot_outline_opacity
        );
        let _ = writeln!(out);
    }

    // --- Бинды
    let binds: Vec<_> = s
        .binds
        .iter()
        .filter(|bnd| !bnd.key.trim().is_empty() && !bnd.command.trim().is_empty())
        .collect();
    if !binds.is_empty() {
        let _ = writeln!(out, "// --- Бинды ---");
        for bnd in binds {
            let _ = writeln!(
                out,
                "bind \"{}\" \"{}\"",
                bnd.key.trim(),
                bnd.command.trim()
            );
        }
        let _ = writeln!(out);
    }

    // --- Свои команды
    if !s.custom_commands.trim().is_empty() {
        let _ = writeln!(out, "// --- Свои команды ---");
        let _ = writeln!(out, "{}", s.custom_commands.trim_end());
        let _ = writeln!(out);
    }

    let _ = writeln!(out, "echo \"[ShaurMeaw] autoexec.cfg loaded\"");
    out
}

/// Собирает список аргументов командной строки для игры.
pub fn build_launch_args(s: &Settings) -> Vec<String> {
    let mut a: Vec<String> = Vec::new();
    let mut push = |v: &str| a.push(v.to_owned());

    if s.novid {
        push("-novid");
    }
    if s.console {
        push("-console");
    }
    if s.dev {
        push("-dev");
    }
    if s.high_priority {
        push("-high");
    }
    if s.nojoy {
        push("-nojoy");
    }
    if s.force_no_vsync_arg {
        push("-forcenovsync");
    }

    match s.render_api {
        RenderApi::Default => {}
        RenderApi::Dx11 => push("-dx11"),
        RenderApi::Vulkan => push("-vulkan"),
    }

    match s.window_mode {
        WindowMode::Default => {}
        WindowMode::Fullscreen => push("-fullscreen"),
        WindowMode::Windowed => push("-windowed"),
        WindowMode::Borderless => {
            push("-windowed");
            push("-noborder");
        }
    }

    if s.custom_resolution {
        push("-w");
        push(&s.width.to_string());
        push("-h");
        push(&s.height.to_string());
    }

    if s.threads > 0 {
        push("-threads");
        push(&s.threads.to_string());
    }

    if !s.language.trim().is_empty() {
        push("-language");
        push(s.language.trim());
    }

    if s.exec_autoexec {
        push("+exec");
        push("autoexec");
    }

    if s.discord_rpc.enabled
        && s.discord_rpc.auto_condebug
        && !s
            .extra_launch_args
            .split_whitespace()
            .any(|arg| arg.eq_ignore_ascii_case("-condebug"))
    {
        push("-condebug");
    }

    for extra in s.extra_launch_args.split_whitespace() {
        push(extra);
    }

    a
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::settings::OptimizationProfile;

    #[test]
    fn test_build_autoexec_and_args_optimization_flags() {
        let mut s = Settings::default();
        s.apply_optimization_profile(OptimizationProfile::EsportsMaxFps);

        let cfg = build_autoexec(&s);
        assert!(cfg.contains("// --- Оптимизация Source 2 (FPS, Input Lag, Сеть, Звук) ---"));
        assert!(cfg.contains("r_low_latency 2"));
        assert!(cfg.contains("engine_low_latency_sleep_after_client_tick 1"));
        assert!(cfg.contains("rate 786432"));
        assert!(cfg.contains("cl_interp_ratio 1"));
        assert!(cfg.contains("cl_interp 0"));
        assert!(cfg.contains("net_maxroutable 1200"));
        assert!(cfg.contains("snd_mixahead 0.025"));
        assert!(cfg.contains("dsp_enhance_stereo 0"));
        assert!(cfg.contains("snd_spatialize_roundrobin 1"));
        assert!(cfg.contains("cl_ragdoll_limit 0"));
        assert!(cfg.contains("r_drawdecals 0"));
        assert!(cfg.contains("r_decals 0"));
        assert!(cfg.contains("lb_enable_shadow_casting 0"));
        assert!(cfg.contains("r_shadows 0"));

        let args = build_launch_args(&s);
        assert!(args.iter().any(|a| a == "-forcenovsync"));

        s.apply_optimization_profile(OptimizationProfile::StandardReset);
        let cfg_std = build_autoexec(&s);
        assert!(!cfg_std.contains("Оптимизация Source 2"));
        assert!(!cfg_std.contains("r_low_latency"));

        let args_std = build_launch_args(&s);
        assert!(!args_std.iter().any(|a| a == "-forcenovsync"));
    }
}
